"""Пример: top-k, top-p и repetition penalty после расчёта логитов.

После forward pass модель отдаёт логиты следующего токена. Дальше можно:

- оставить фиксированное число лучших кандидатов — ``top_k``;
- оставить минимальный набор с суммарной вероятностью не меньше порога —
  ``top_p``;
- снизить оценки уже встречавшихся токенов — ``repetition_penalty``.

Эти механизмы не заменяют температуру. Температура меняет форму
распределения. top-k и top-p режут множество кандидатов. Repetition penalty
смотрит на историю: положительный логит встреченного токена делится на штраф,
отрицательный умножается. В обоих случаях оценка становится меньше.

Greedy decoding выбирает только максимум. Поэтому несколько разных штрафов
могут дать один и тот же текст: логиты отличаются, а максимальный токен
на каждом шаге один и тот же. Небольшое изменение, например с 1.0 до 1.05,
иногда сразу переключает траекторию.

В первой части пример гоняет ``gpt2`` на русском промпте «Это очень очень»
и показывает, как ``repetition_penalty`` влияет на продолжение. Модель
обучена в основном на английском, поэтому текст может уходить в английские
фразы. Важно не дословное совпадение с уроком, а исчезновение цикла.

Во второй части три учебных кейса работают на заранее заданных логитах:

1. Зацикливание — уже встречавшийся токен снова максимальный.
   Подходит минимальный ``repetition_penalty``, после которого выбирается
   новый токен: ``1.05``.
2. Нет разнообразия — при узком top-k все seed выбирают один токен.
   Минимальный ``top_k``, при котором появляется не меньше трёх разных
   токенов: ``3``. Seed отличаются от урока: на torch 2.2.2 RNG другой,
   поэтому подобраны значения, которые дают тот же педагогический итог.
   Температура при ``top_k=1`` не помогла бы: после фильтрации всё равно
   остался бы один кандидат.
3. Длинный хвост — слабый токен `` DNS`` участвует в sampling.
   Нужен максимальный ``top_p``, который уже исключает его: ``0.95``.
   Так хвост отрезается, а множество подходящих кандидатов остаётся
   максимально широким.

Запуск из корня проекта:

    python example_decoding_controls.py
"""

import importlib.util
import sys

if importlib.util.find_spec("torch") is None:
    sys.exit(
        "Для этого примера нужен torch: модель gpt2 хранит веса в нём.\n"
        "Поставьте зависимости из requirements.txt: на этом Intel Mac это torch==2.2.2."
    )

from utils.models import (
    diagnose_decoding_controls,
    generate_greedy_text,
    load_causal_model,
)

PROMPT = "Это очень очень"
PENALTIES = [1.0, 1.05, 1.1, 1.2, 1.3, 2.0, 10.0]


def main() -> None:
    print("1. Greedy на gpt2: repetition penalty против зацикливания")
    tokenizer, model = load_causal_model("gpt2")
    print("Промпт:", PROMPT)

    for penalty in PENALTIES:
        text = generate_greedy_text(
            model=model,
            tokenizer=tokenizer,
            prompt=PROMPT,
            repetition_penalty=penalty,
            max_new_tokens=35,
        )
        print("=" * 80)
        print(f"repetition_penalty = {penalty}")
        print("=" * 80)
        print(text)
        print()

    print("Как читать первую часть")
    print(
        "1.0 — штраф выключен: уже встречавшиеся токены могут снова стать "
        "максимумом и закрепить цикл."
    )
    print(
        "Небольшой рост штрафа иногда сразу меняет первый максимум, "
        "после чего вся траектория уходит в сторону."
    )
    print(
        "Несколько разных значений могут дать один текст: greedy смотрит "
        "только на порядок логитов, а не на их абсолютную разницу."
    )
    print(
        "Сильный штраф не всегда безопасен: он может мешать нужным повторам "
        "в коде, JSON, именах и терминах."
    )

    print("\n2. Три учебных кейса на заранее заданных логитах")
    case_1, case_2, case_3, diagnosis = diagnose_decoding_controls()

    print("\nКейс 1. Repetition penalty:")
    print(case_1.to_string(index=False))

    print("\nКейс 2. Top-k:")
    print(case_2.to_string(index=False))

    print("\nКейс 3. Top-p:")
    print(case_3.to_string(index=False))

    print("\nИтоговая диагностика:")
    print(diagnosis.to_string(index=False))

    print("\nПочему выбран именно этот механизм")
    print(
        "Зацикливание связано с историей токенов, поэтому нужен "
        "repetition_penalty, а не top-k/top-p."
    )
    print(
        "При top_k=1 температура не даст разнообразия: после фильтрации "
        "останется один кандидат."
    )
    print(
        "Для хвоста берут наибольший подходящий top_p: проблемный токен "
        "уже отрезан, а множество кандидатов ещё широкое."
    )


if __name__ == "__main__":
    main()
