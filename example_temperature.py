"""Пример: температура управляет случайностью sampling.

На каждом шаге модель считает логиты следующего токена. Температура делит
эти логиты перед softmax. Порядок кандидатов не меняется: самый вероятный
токен остаётся самым вероятным. Меняется острота распределения.

- Низкая температура делает распределение острым: модель чаще берёт
  самые вероятные токены. Текст стабильнее, формат строже, но сюжет
  может стать шаблонным и повторяющимся.
- Высокая температура делает распределение ровнее: реже вероятные токены
  получают больше шансов. Появляются необычные детали, но связность
  и точность инструкции страдают чаще.
- ``temperature = 0`` в этом примере означает greedy decoding:
  ``do_sample=False``. Параметр ``temperature=0`` в ``generate`` не передаётся,
  потому что без sampling температура случайностью не управляет.

Функция ``generate_text`` возвращает только продолжение после промпта.
Это удобно сравнивать ответы: исходный текст не мешает читать разницу.

Модель урока — ``roneneldan/TinyStories-Instruct-33M``. Она маленькая,
поэтому сравнение температур видно на CPU. Промпт здесь на русском, хотя
сама модель обучалась в основном на английских сказках: продолжения могут
быть слабее, чем в уроке, но разница между температурами всё равно видна.
Один и тот же промпт и seed дают воспроизводимый эксперимент.

Запуск из корня проекта:

    python example_temperature.py
"""

import importlib.util
import sys

if importlib.util.find_spec("torch") is None:
    sys.exit(
        "Для этого примера нужен torch: модель TinyStories хранит веса в нём.\n"
        "Поставьте зависимости из requirements.txt: на этом Intel Mac это torch==2.2.2."
    )

from utils.models import generate_text, load_causal_model

MODEL_NAME = "roneneldan/TinyStories-Instruct-33M"
TEMPERATURES = [0, 0.7, 1.5]
PROMPT = """
Жил-был маленький робот, который хотел вырастить сад.
Каждое утро робот смотрел на семена и
"""


def main() -> None:
    print("Модель:", MODEL_NAME)
    tokenizer, model = load_causal_model(MODEL_NAME)

    print("Промпт:")
    print(PROMPT.strip())
    print()

    for temperature in TEMPERATURES:
        print("=" * 80)
        print(f"temperature = {temperature}")
        print("=" * 80)
        continuation = generate_text(
            model=model,
            tokenizer=tokenizer,
            prompt=PROMPT,
            temperature=temperature,
            max_new_tokens=120,
            seed=42,
        )
        print(continuation)
        print()

    print("Как читать разницу")
    print(
        "0: greedy, текст обычно связный и завершённый, но простой и шаблонный."
    )
    print(
        "0.7: sampling ещё достаточно спокойный, появляются конкретные действия "
        "и детали, иногда лишний элемент формата вроде «Краткое содержание»."
    )
    print(
        "1.5: больше образности и неожиданных деталей, но выше риск странных "
        "переходов и неестественных фраз."
    )


if __name__ == "__main__":
    main()
